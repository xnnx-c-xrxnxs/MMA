export const renderRepositoryInterface = (ctx: DomainContext): string => {
  const { entity, statuses } = ctx;
  const statusType = statuses.length > 0 ? `${entity.pascal}Status` : 'string';
  const statusImport =
    statuses.length > 0
      ? `import { ${entity.pascal}Status } from '../../domain/constants';\n`
      : '';
  const listByStatusBlock =
    statuses.length > 0
      ? `
  /**
   * List ${entity.camelPlural} by status with cursor-based pagination.
   */
  abstract listByStatus(
    ${entity.camel}Status: ${statusType},
    limit?: number,
    direction?: string,
    nextCursorPointer?: string,
    prevCursorPointer?: string,
  ): Promise<IPaginatedResponse<${entity.pascal}>>;
`
      : '';

  return `import { IPaginatedResponse } from '@old-st/common';
${statusImport}import { ${entity.pascal} } from '../../domain/entities';

export abstract class I${entity.pascal}Repository {
  abstract save(${entity.camel}: ${entity.pascal}): Promise<${entity.pascal}>;

  abstract findById(${entity.camel}Id: string): Promise<${entity.pascal} | null>;
${listByStatusBlock}}
`;
};

